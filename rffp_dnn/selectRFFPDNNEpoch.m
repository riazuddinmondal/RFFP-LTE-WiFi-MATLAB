function [bestEpoch,info] = selectRFFPDNNEpoch(XFit,YFit,XVal,YVal,cfg)
%SELECTRFFPDNNEPOCH Select epoch count using complete held-out routes.

[YFitN,YValN,center,scale] = normalizeTargets(YFit,YVal);
layers = buildRFFPMLP(size(XFit,2),cfg);
iterationsPerEpoch = max(1,ceil(size(XFit,1)/cfg.MiniBatchSize));
validationFrequency = iterationsPerEpoch;

options = trainingOptions('adam', ...
    'ExecutionEnvironment',char(cfg.ExecutionEnvironment), ...
    'InitialLearnRate',cfg.InitialLearnRate, ...
    'LearnRateSchedule','piecewise', ...
    'LearnRateDropFactor',cfg.LearnRateDropFactor, ...
    'LearnRateDropPeriod',cfg.LearnRateDropPeriod, ...
    'L2Regularization',cfg.L2Regularization, ...
    'MiniBatchSize',cfg.MiniBatchSize, ...
    'MaxEpochs',cfg.MaxValidationEpochs, ...
    'Shuffle','every-epoch', ...
    'ValidationData',{XVal,YValN}, ...
    'ValidationFrequency',validationFrequency, ...
    'ValidationPatience',cfg.ValidationPatience, ...
    'Verbose',cfg.Verbose, ...
    'VerboseFrequency',validationFrequency, ...
    'Plots','none');

[~,info] = trainNetwork(XFit,YFitN,layers,options);
validationLoss = info.ValidationLoss;
valid = find(isfinite(validationLoss));
if isempty(valid)
    warning('RFFP:DNNNoValidationLoss', ...
        'No finite validation loss was returned; using maximum epochs.');
    bestEpoch = cfg.MaxValidationEpochs;
else
    [~,localIndex] = min(validationLoss(valid));
    bestIteration = valid(localIndex);
    bestEpoch = ceil(bestIteration/iterationsPerEpoch);
end
bestEpoch = max(cfg.MinimumFinalEpochs,min(cfg.MaxValidationEpochs,bestEpoch));
info.TargetCenter = center;
info.TargetScale = scale;
info.IterationsPerEpoch = iterationsPerEpoch;
info.SelectedEpoch = bestEpoch;
end

function [A,B,center,scale] = normalizeTargets(YFit,YVal)
center = mean(YFit,1);
scale = std(YFit,0,1);
scale(scale==0 | ~isfinite(scale)) = 1;
A = single((double(YFit)-center)./scale);
B = single((double(YVal)-center)./scale);
end

