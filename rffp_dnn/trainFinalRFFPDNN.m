function [net,targetCenter,targetScale,info] = trainFinalRFFPDNN( ...
    XTrain,YTrain,numEpochs,cfg)
%TRAINFINALRFFPDNN Retrain on every outer-training route for chosen epochs.

targetCenter = mean(YTrain,1);
targetScale = std(YTrain,0,1);
targetScale(targetScale==0 | ~isfinite(targetScale)) = 1;
YTrainN = single((double(YTrain)-targetCenter)./targetScale);
layers = buildRFFPMLP(size(XTrain,2),cfg);
iterationsPerEpoch = max(1,ceil(size(XTrain,1)/cfg.MiniBatchSize));

options = trainingOptions('adam', ...
    'ExecutionEnvironment',char(cfg.ExecutionEnvironment), ...
    'InitialLearnRate',cfg.InitialLearnRate, ...
    'LearnRateSchedule','piecewise', ...
    'LearnRateDropFactor',cfg.LearnRateDropFactor, ...
    'LearnRateDropPeriod',cfg.LearnRateDropPeriod, ...
    'L2Regularization',cfg.L2Regularization, ...
    'MiniBatchSize',cfg.MiniBatchSize, ...
    'MaxEpochs',numEpochs, ...
    'Shuffle','every-epoch', ...
    'Verbose',cfg.Verbose, ...
    'VerboseFrequency',iterationsPerEpoch, ...
    'Plots','none');

[net,info] = trainNetwork(XTrain,YTrainN,layers,options);
end

