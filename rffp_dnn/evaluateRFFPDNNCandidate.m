function [score,M,bestEpoch,info] = evaluateRFFPDNNCandidate( ...
    XFit,YFit,XVal,YVal,cfg)
%EVALUATERFFPDNNCANDIDATE Train and score one inner grouped-validation run.

center=mean(YFit,1); scale=std(YFit,0,1);
scale(scale==0|~isfinite(scale))=1;
YFitN=single((double(YFit)-center)./scale);
YValN=single((double(YVal)-center)./scale);
layers=buildRFFPMLP(size(XFit,2),cfg);
ipe=max(1,ceil(size(XFit,1)/cfg.MiniBatchSize));

options=trainingOptions('adam', ...
    'ExecutionEnvironment',char(cfg.ExecutionEnvironment), ...
    'InitialLearnRate',cfg.InitialLearnRate, ...
    'LearnRateSchedule','piecewise', ...
    'LearnRateDropFactor',cfg.LearnRateDropFactor, ...
    'LearnRateDropPeriod',cfg.LearnRateDropPeriod, ...
    'L2Regularization',cfg.L2Regularization, ...
    'MiniBatchSize',cfg.MiniBatchSize, ...
    'MaxEpochs',cfg.MaxValidationEpochs, ...
    'Shuffle','every-epoch', ...
    'ValidationData',{XVal,YValN}, ...
    'ValidationFrequency',ipe, ...
    'ValidationPatience',cfg.ValidationPatience, ...
    'OutputNetwork','best-validation-loss', ...
    'Verbose',false,'Plots','none');

[net,info]=trainNetwork(XFit,YFitN,layers,options);
loss=info.ValidationLoss; valid=find(isfinite(loss));
if isempty(valid)
    bestEpoch=cfg.MaxValidationEpochs;
else
    [~,j]=min(loss(valid));
    bestEpoch=ceil(valid(j)/ipe);
end
bestEpoch=max(cfg.MinimumFinalEpochs,min(cfg.MaxValidationEpochs,bestEpoch));
pn=predict(net,XVal,'MiniBatchSize',cfg.PredictionMiniBatchSize);
pred=double(pn).*scale+center;
M=positioningMetrics(YVal,pred);
score=M.Mean_m + cfg.TailWeight*M.P95_m;
end

