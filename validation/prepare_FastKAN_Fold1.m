%% Independent hierarchical FastKAN V2 C Fold 1
clear; clc;
root='C:\RFFP_Release_Validation';
softwareDir=fullfile(root,'software');
dataFile=fullfile(root,'private_data','RFFP_corrected_representations.mat');
foldFile=fullfile(root,'reference','corrected_route10fold_checkpoint.mat');
outDir=fullfile(root,'test_outputs','FastKAN_Level3_Fold1');
assert(isfile(dataFile),'Missing dataset: %s',dataFile);
assert(isfile(foldFile),'Missing reference fold file: %s',foldFile);
if ~isfolder(outDir),mkdir(outDir);end
assert(~isfile(fullfile(outDir,'FastKAN_V2_fold1_results.mat')), ...
    'Existing validation result found; move it before a fresh independent run.');
addpath(genpath(softwareDir));
assert(~isempty(which('run_RFFP_Hierarchical_FastKAN_V2')), 'V2 runner not found');
assert(~isempty(which('FastKANLayer')), 'FastKANLayer not found');
% Verify fold vector shape; V2 runner itself reads savedFoldIndex from FoldFile.
R=load(foldFile,'savedFoldIndex');
assert(numel(R.savedFoldIndex)==118930 && nnz(R.savedFoldIndex==1)==12651, ...
    'Unexpected Fold 1 reference partition.');
% These values match the archived fastkan_config.json in the public results.
% DO NOT substitute the older non-V2 FastKAN program or quick-test settings.
tic;
r=run_RFFP_Hierarchical_FastKAN_V2(dataFile,1, ...
    'FoldFile',foldFile,'OutputDir',outDir, ...
    'Epochs',100,'BatchSize',1024,'LearningRate',0.002, ...
    'WeightDecay',2e-5,'Patience',12,'NumGrids',12, ...
    'Dropout',0.04,'RSSJitter_dB',1.2, ...
    'CandidateFeatures',768,'GlobalFeatures',256, ...
    'LocalFeatures',160,'MinExpertSamples',1500, ...
    'MaxExperts',15,'FusionStep',0.05, ...
    'MinFusionImprovement',0.002,'FusionObjective','hybrid', ...
    'MinExpertValSamples',100,'Seed',17, ...
    'ExecutionEnvironment','auto');
wallClock_s=toc;
save(fullfile(outDir,'FastKAN_Level3_WallClock.mat'),'wallClock_s');
fprintf('FastKAN V2 Fold 1 completed in %.2f seconds.\n',wallClock_s);
