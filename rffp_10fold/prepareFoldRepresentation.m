function [XTrain,XTest,featureInfo] = prepareFoldRepresentation(reps,name,trainMask,testMask,cfg)
%PREPAREFOLDREPRESENTATION Materialize one representation for one fold.

trainRows=find(trainMask); testRows=find(testMask);
switch upper(string(name))
    case "A"
        ids=reps.A_rankPairs.IDs;
        p=reps.A_rankPairs.Power_dBm;
        use=[trainRows;testRows]; ids=ids(use,:); p=p(use,:);
        isWLAN=ids>=200000;
        floors=repmat(single(cfg.LTEMissingFloor_dBm),size(p));
        floors(isWLAN)=single(cfg.WLANMissingFloor_dBm);
        p(~isfinite(p))=floors(~isfinite(p));
        % This is intentionally the direct numeric-ID baseline. Scaling is
        % learned below from training data only.
        X=[single(double(ids)/200000),p,single(ids~=0)];
        XTrain=X(1:numel(trainRows),:); XTest=X(numel(trainRows)+1:end,:);
        featureInfo=struct('Encoding','ranked numeric ID + power + detection');
    case "B"
        [XTrain,featureInfo]=materializeTopKCategoricalRFFP(reps.B_topK,trainMask,trainRows, ...
            MinTrainingObservations=cfg.MinTrainingObservations, ...
            MaxLTEIdentities=cfg.MaxLTEFeatures,MaxWLANIdentities=cfg.MaxWLANFeatures, ...
            LTEMissingFloor_dBm=cfg.LTEMissingFloor_dBm, ...
            WLANMissingFloor_dBm=cfg.WLANMissingFloor_dBm,IncludeDetectionMask=true);
        XTest=materializeTopKCategoricalRFFP(reps.B_topK,trainMask,testRows, ...
            MinTrainingObservations=cfg.MinTrainingObservations, ...
            MaxLTEIdentities=cfg.MaxLTEFeatures,MaxWLANIdentities=cfg.MaxWLANFeatures, ...
            LTEMissingFloor_dBm=cfg.LTEMissingFloor_dBm, ...
            WLANMissingFloor_dBm=cfg.WLANMissingFloor_dBm,IncludeDetectionMask=true);
    case "C"
        [XTrain,featureInfo]=materializeAlignedRFFP(reps.C_alignedSparse,trainMask,trainRows, ...
            MinTrainingObservations=cfg.MinTrainingObservations, ...
            MaxLTEFeatures=cfg.MaxLTEFeatures,MaxWLANFeatures=cfg.MaxWLANFeatures, ...
            LTEMissingFloor_dBm=cfg.LTEMissingFloor_dBm, ...
            WLANMissingFloor_dBm=cfg.WLANMissingFloor_dBm,IncludeDetectionMask=true);
        XTest=materializeAlignedRFFP(reps.C_alignedSparse,trainMask,testRows, ...
            MinTrainingObservations=cfg.MinTrainingObservations, ...
            MaxLTEFeatures=cfg.MaxLTEFeatures,MaxWLANFeatures=cfg.MaxWLANFeatures, ...
            LTEMissingFloor_dBm=cfg.LTEMissingFloor_dBm, ...
            WLANMissingFloor_dBm=cfg.WLANMissingFloor_dBm,IncludeDetectionMask=true);
    otherwise
        error('Unknown representation %s.',name);
end

% Scale for distance-based methods and improve numerical conditioning. Zero
% variance columns remain unchanged. Parameters come from training only.
mu=mean(XTrain,1,'omitnan'); sigma=std(XTrain,0,1,'omitnan'); sigma(sigma==0|~isfinite(sigma))=1;
XTrain=single((double(XTrain)-mu)./sigma);
XTest=single((double(XTest)-mu)./sigma);
representationInfo=featureInfo;
featureInfo=struct('RepresentationInfo',representationInfo, ...
    'StandardizationMean',mu,'StandardizationStd',sigma);
end
